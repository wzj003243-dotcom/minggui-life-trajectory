-- Private thickness calculation.
create or replace view research.person_thickness_v1
with (security_invoker=true) as
select
  p.id person_id,p.wikidata_id,p.canonical_name,
  count(e.id)::int event_count,
  count(distinct e.domain)::int domain_count,
  count(distinct e.source_family)::int source_family_count,
  count(distinct case
    when e.age_mid>=0 and e.age_mid<18 then '0-17'
    when e.age_mid>=18 and e.age_mid<25 then '18-24'
    when e.age_mid>=25 and e.age_mid<35 then '25-34'
    when e.age_mid>=35 and e.age_mid<50 then '35-49'
    when e.age_mid>=50 and e.age_mid<65 then '50-64'
    when e.age_mid>=65 then '65+'
  end)::int life_stage_count,
  min(e.age_mid) first_observed_event_age,
  max(e.age_mid) last_observed_event_age,
  (
    count(e.id)>=15
    and count(distinct e.domain)>=4
    and count(distinct case
      when e.age_mid>=0 and e.age_mid<18 then '0-17'
      when e.age_mid>=18 and e.age_mid<25 then '18-24'
      when e.age_mid>=25 and e.age_mid<35 then '25-34'
      when e.age_mid>=35 and e.age_mid<50 then '35-49'
      when e.age_mid>=50 and e.age_mid<65 then '50-64'
      when e.age_mid>=65 then '65+'
    end)>=3
    and count(distinct e.source_family)>=2
  ) model_ready_thick
from research.people p
left join research.life_events e on e.person_id=p.id and e.model_eligible
group by p.id,p.wikidata_id,p.canonical_name;

grant select on research.person_thickness_v1 to service_role;

-- Curated Data API contract. These views are intentionally server-only.
create or replace view public.lifegraph_people_v1
with (security_invoker=true) as
select
  p.id,p.wikidata_id,p.canonical_name,p.gender,
  b.birth_date,b.birth_time,b.birth_time_known,b.birth_place,b.birth_country,b.reliability birth_reliability,
  bf.feature_version bazi_feature_version,bf.four_pillars,
  t.event_count,t.domain_count,t.source_family_count,t.life_stage_count,t.model_ready_thick
from research.people p
left join research.birth_records b on b.person_id=p.id and b.is_canonical
left join lateral (
  select bf0.*
  from research.bazi_feature_sets bf0
  left join research.dataset_snapshots ds on ds.id=bf0.source_snapshot_id
  where bf0.person_id=p.id and bf0.mode='timed'
  order by ds.created_at desc nulls last,bf0.created_at desc,bf0.id desc
  limit 1
) bf on true
left join research.person_thickness_v1 t on t.person_id=p.id;

