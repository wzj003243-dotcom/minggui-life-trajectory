-- RLS/private schema.
do $$
declare t text;
begin
  foreach t in array array[
    'training_task_definitions','training_dataset_versions','training_examples','training_person_splits',
    'training_split_scenarios','training_split_assignments','feature_variant_definitions','training_audit_results',
    'model_runs','model_predictions','model_metrics','model_artifacts',
    'data_quality_issues','event_candidates','event_adjudications'
  ]
  loop
    execute format('alter table research.%I enable row level security',t);
    execute format('drop policy if exists %I on research.%I','service_role_all_'||t,t);
    execute format('create policy %I on research.%I for all to service_role using (true) with check (true)','service_role_all_'||t,t);
    execute format('revoke all on research.%I from public,anon,authenticated',t);
    execute format('grant select,insert,update,delete on research.%I to service_role',t);
  end loop;
end $$;

-- Server-only views.
create or replace view research.training_next_event_domain_v1
with (security_invoker=true) as
select e.*,
  case
    when e.target_domain in ('career','recognition','relationship') then e.target_domain
    when e.target_domain is null then null
    else 'other'
  end target_class_4
from research.training_examples e;

create or replace view research.training_dataset_readiness_v1
with (security_invoker=true) as
select
  td.id,td.dataset_key,td.version,td.status,td.row_count,td.person_count,td.fingerprint_sha256,
  count(ar.id) filter(where ar.severity='error')::int error_audit_count,
  count(ar.id) filter(where ar.severity='error' and not ar.passed)::int failed_error_audits,
  count(ar.id) filter(where ar.severity='warning')::int warning_count,
  (count(ar.id) filter(where ar.severity='error' and not ar.passed)=0 and td.status='frozen') training_ready,
  td.metadata
from research.training_dataset_versions td
left join research.training_audit_results ar on ar.training_dataset_id=td.id
group by td.id;

grant select on research.training_next_event_domain_v1,research.training_dataset_readiness_v1 to service_role;
