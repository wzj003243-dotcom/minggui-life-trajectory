-- MingGui training/experiment schema v1
-- Apply after supabase/lifegraph_v2.sql.
-- Research tables are server-only and protected with RLS + service_role policies.

create table if not exists research.training_task_definitions (
  task_key text primary key,
  task_version text not null,
  description text not null,
  target_semantics text not null,
  cutoff_ages integer[] not null,
  target_schema jsonb not null,
  inclusion_policy jsonb not null,
  censoring_policy jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists research.training_dataset_versions (
  id uuid primary key default gen_random_uuid(),
  dataset_key text not null,
  version text not null,
  task_key text not null references research.training_task_definitions(task_key),
  source_snapshot_id uuid not null references research.dataset_snapshots(id),
  feature_spec_version text not null,
  split_spec_version text not null,
  status text not null default 'draft',
  row_count integer,
  person_count integer,
  fingerprint_sha256 text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  frozen_at timestamptz,
  unique(dataset_key,version)
);

create table if not exists research.training_examples (
  id bigint generated by default as identity primary key,
  training_dataset_id uuid not null references research.training_dataset_versions(id) on delete cascade,
  person_id bigint not null references research.people(id) on delete cascade,
  cutoff_age integer not null check(cutoff_age>0),
  cutoff_date date not null,
  information_cutoff date not null,
  history_event_count integer not null default 0,
  history_domain_count integer not null default 0,
  history_source_family_count integer not null default 0,
  history_life_stage_count integer not null default 0,
  history_summary jsonb not null default '{}'::jsonb,
  target_event_key text references research.life_events(event_key) on update cascade on delete restrict,
  target_domain text,
  target_event_type text,
  target_observable_from date,
  target_age double precision,
  target_payload jsonb not null default '{}'::jsonb,
  observation_end_date date,
  right_censored boolean not null default false,
  censoring_reason text,
  observation_profile jsonb not null default '{}'::jsonb,
  split_name text,
  fold integer,
  split_group text,
  eligibility_flags jsonb not null default '{}'::jsonb,
  sample_weight double precision,
  weight_method text,
  created_at timestamptz not null default now(),
  unique(training_dataset_id,person_id,cutoff_age),
  constraint training_examples_history_counts_nonnegative check(
    history_event_count>=0 and history_domain_count>=0
    and history_source_family_count>=0 and history_life_stage_count>=0
  )
);

create table if not exists research.training_person_splits (
  training_dataset_id uuid not null references research.training_dataset_versions(id) on delete cascade,
  person_id bigint not null references research.people(id) on delete cascade,
  split_name text not null,
  fold integer,
  strategy text not null,
  split_group text not null,
  assignment_hash text not null,
  primary key(training_dataset_id,person_id)
);

create table if not exists research.training_split_scenarios (
  scenario_key text primary key,
  scenario_version text not null,
  description text not null,
  policy jsonb not null,
  created_at timestamptz not null default now()
