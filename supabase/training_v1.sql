create table if not exists research.model_runs (
  id uuid primary key default gen_random_uuid(),
  training_dataset_id uuid not null references research.training_dataset_versions(id) on delete restrict,
  run_key text not null unique,
  model_family text not null,
  feature_variant text not null,
  split_scenario_key text not null references research.training_split_scenarios(scenario_key),
