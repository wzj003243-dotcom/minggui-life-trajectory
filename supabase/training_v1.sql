create table if not exists research.training_split_assignments (
  training_dataset_id uuid not null references research.training_dataset_versions(id) on delete cascade,
  scenario_key text not null references research.training_split_scenarios(scenario_key),
  person_id bigint not null references research.people(id) on delete cascade,
  split_name text not null,
  fold integer,
  split_group text not null,
  assignment_basis jsonb not null default '{}'::jsonb,
  primary key(training_dataset_id,scenario_key,person_id)
);

create table if not exists research.feature_variant_definitions (
  feature_variant_key text primary key,
  variant_version text not null,
  description text not null,
  feature_policy jsonb not null,
  placebo boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists research.training_audit_results (
  id bigint generated by default as identity primary key,
  training_dataset_id uuid not null references research.training_dataset_versions(id) on delete cascade,
  audit_key text not null,
