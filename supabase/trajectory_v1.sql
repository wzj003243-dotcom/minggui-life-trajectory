create or replace view research.trajectory_cutoff_matrix_v1
with (security_invoker=true) as
select
  pp.training_dataset_id,
  pp.source_training_example_id,
  pp.person_id,
  p.wikidata_id,
  te.cutoff_age,
  te.cutoff_date,
  te.information_cutoff,
  te.target_canonical_event_key source_target_canonical_event_key,
  te.target_domain source_target_domain,
  te.target_observable_from source_target_observable_from,
  te.observation_end_date source_observation_end_date,
  te.right_censored source_right_censored,
  fs.features x_features,
  fs.included_event_keys provenance_raw_history_event_keys,
  fs.included_canonical_event_keys modeled_history_canonical_event_keys,
  jsonb_agg(
    jsonb_build_object(
      'interval_index',pp.interval_index,
      'start_year',pp.interval_start_year,
      'end_year',pp.interval_end_year,
      'start_date',pp.interval_start_date,
      'end_date',pp.interval_end_date,
      'width_years',pp.interval_width_years,
      'outcome_class',pp.outcome_class,
      'event_observed',pp.event_observed
    ) order by pp.interval_index
  ) periods
from research.trajectory_person_period_examples pp
join research.training_examples te on te.id=pp.source_training_example_id
join research.people p on p.id=pp.person_id
join research.feature_snapshots fs
  on fs.person_id=pp.person_id
 and fs.information_cutoff=te.information_cutoff
 and fs.source_snapshot_id='42628250-3a51-4b92-b4bd-12c7dec846a8'::uuid
 and fs.feature_spec_version='bazi-objective-v0.1+canonical-history-v1'
 and fs.leakage_audit_passed
where pp.training_dataset_id='731fa601-9c18-4ce8-9a8a-557ded47395d'::uuid
group by
  pp.training_dataset_id,pp.source_training_example_id,pp.person_id,p.wikidata_id,
  te.cutoff_age,te.cutoff_date,te.information_cutoff,te.target_canonical_event_key,
  te.target_domain,te.target_observable_from,te.observation_end_date,te.right_censored,
  fs.features,fs.included_event_keys,fs.included_canonical_event_keys;

