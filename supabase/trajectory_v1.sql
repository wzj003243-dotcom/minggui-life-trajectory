-- Official frozen derived dataset:
-- ID 731fa601-9c18-4ce8-9a8a-557ded47395d
-- fingerprint 9e2de5961856ad79ae260cb87fea1028f38b278c74eb3ff7669d94a35cf9f7c3
-- 52,427 person-period rows; 13,064 cutoff states; 3,382 people; 6,060 event rows.

with base as (
  select
    te.*,
    psf.birth_date,
    psf.death_date,
    psf.death_year,
    case
      when te.target_observable_from is null
       and psf.death_date is null
       and psf.death_year is null
       and ((date '2026-10-05' - psf.birth_date)/365.2425) > 100
      then true else false
    end as ambiguous_unknown_death_exposure
  from research.training_examples te
  join research.person_snapshot_facts psf
    on psf.dataset_snapshot_id='42628250-3a51-4b92-b4bd-12c7dec846a8'::uuid
   and psf.person_id=te.person_id
  where te.training_dataset_id='8261f970-adc3-4f9a-8043-9e0f6cb90be8'::uuid
    and coalesce((te.eligibility_flags->>'censor_aware_eligible')::boolean,false)
), intervals(interval_index,start_year,end_year) as (
  values (0,0,1),(1,1,3),(2,3,5),(3,5,10),(4,10,20)
), expanded as (
  select
    b.id source_training_example_id,
    b.person_id,b.cutoff_age,b.cutoff_date,b.information_cutoff,
    i.interval_index,i.start_year,i.end_year,
    (b.cutoff_date+make_interval(years=>i.start_year))::date interval_start_date,
    (b.cutoff_date+make_interval(years=>i.end_year))::date interval_end_date,
    b.target_domain,b.target_canonical_event_key,b.target_observable_from,
    b.observation_end_date,b.right_censored,b.ambiguous_unknown_death_exposure
  from base b cross join intervals i
), risk as (
  select *,
    (
      target_observable_from is not null
      and target_observable_from>interval_start_date
      and target_observable_from<=interval_end_date
    ) event_observed
  from expanded
  where
    (
      target_observable_from is not null
      and interval_start_date<target_observable_from
    )
    or
    (
      target_observable_from is null
      and not ambiguous_unknown_death_exposure
      and interval_end_date<=observation_end_date
    )
)
