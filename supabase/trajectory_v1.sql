  outcome_class,event_observed,target_domain,target_canonical_event_key,target_observable_from,observation_end_date,
  source_right_censored,exposure_policy_key,source_feature_spec_version
)
select
  '731fa601-9c18-4ce8-9a8a-557ded47395d'::uuid,
  source_training_example_id,person_id,cutoff_age,cutoff_date,information_cutoff,
  interval_index,start_year,end_year,interval_start_date,interval_end_date,end_year-start_year,
