"""Create canonical-birth compatible table from the timed linked cohort.

The normalized Gregorian physical date generated by the BaZi feature builder is used for age
arithmetic. Original source calendar/date remains in the linked table for provenance.
"""
from __future__ import annotations
import argparse,csv,gzip,json
from pathlib import Path

def main():
    ap=argparse.ArgumentParser();ap.add_argument("linked");ap.add_argument("output");args=ap.parse_args()
    out=Path(args.output);out.parent.mkdir(parents=True,exist_ok=True)
    fields=["wikidata_id","birth_date","canonical_status","source","rodden_rating","adb_id"]
    n=0
    with gzip.open(args.linked,"rt",encoding="utf-8",newline="") as f,gzip.open(out,"wt",encoding="utf-8",newline="") as w:
        r=csv.DictReader(f);wr=csv.DictWriter(w,fieldnames=fields);wr.writeheader()
        for x in r:
            if not x.get("wikidata_id") or not x.get("birth_date_normalized"):continue
            wr.writerow({
              "wikidata_id":x["wikidata_id"],"birth_date":x["birth_date_normalized"],
              "canonical_status":"canonical_unique","source":"astro-databank-timed",
              "rodden_rating":x.get("rodden_rating",""),"adb_id":x.get("adb_id","")
            });n+=1
    report={"canonical_birth_rows":n,"date_semantics":"normalized Gregorian physical date for age arithmetic"}
    out.with_name(out.name[:-7]+".report.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    print(json.dumps(report,indent=2))
if __name__=="__main__":main()
